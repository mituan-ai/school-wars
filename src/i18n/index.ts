export type TextKey = keyof typeof zh;

const dicts: Record<Lang, Record<TextKey, string>> = { zh, en };
let current: Lang = 'zh';

export function setLang(lang: Lang): void {
  current = lang;
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
}

export function getLang(): Lang {
  return current;
}

export function t(key: TextKey, params: Record<string, string | number> = {}): string {
  return dicts[current][key].replace(/\{(\w+)\}/g, (_m, k: string) => String(params[k] ?? ''));
}

export function factionName(col: number, short = false): string {
  return t(`faction.${short ? 'short.' : ''}${col}` as TextKey);
}

export function formatTime(ticks: number): string {
  const s = Math.floor(ticks / 18);
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
}
